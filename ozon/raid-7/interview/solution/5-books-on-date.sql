-- Задача 5: сколько книг было на руках 1 мая (исторический срез).
-- Проверено на PostgreSQL, в т.ч. по дням 30.04–05.05: взяли 1-го,
-- вернули 3-го, 4-го взял другой — срезы 1,2 → 2; 3 → 2; 4,5 → 3.

SELECT count(*) AS on_hands
FROM loans l
WHERE l.taken_at <= DATE '2026-05-01'
  AND (l.returned_at IS NULL OR l.returned_at > DATE '2026-05-01');

-- Семантика дат договорённость: taken_at <= D — «выдана не позже D»,
-- returned_at > D — «не сдана до конца дня D» (в день возврата книга
-- уже не числится на руках). Диапазон полуоткрытый, как интервалы
-- в tempdb-задачах: [taken_at, returned_at) по дням владения.

-- Когда исторический срез перестаёт давать верный результат:
-- 1. Схема хранит только текущего держателя (books.visitor_id без loans) —
--    среза нет вовсе; вся прошлая информация затёрта.
-- 2. Повторные выдачи без истории: если loans перезаписывать, а не
--    добавлять строкой на каждую выдачу, интервалы прошлого теряются.
-- 3. returned_at проставляется задним числом (сдал 3-го, отметили 5-го) —
--    срез на 4-е ложно считает книгу на руках. Лечится источником истины:
--    отметка в момент события, дата факта, не дата записи.
-- 4. Часовые пояса/тип колонки: date против timestamptz дают разные
--    границы дня; надо зафиксировать и не смешивать.

-- Медленные запросы в проде и индексы:
-- 1. Срез: частичный индекс не поможет по исторической части —
--    индекс на интервал:
--      CREATE INDEX ON loans (taken_at, returned_at);
--    запрос читает диапазон taken_at <= D и фильтрует returned_at;
--    btree по двум колонкам закрывает и фильтр.
-- 2. «Кто держит сейчас»: частичный индекс дешевле полного скана:
--      CREATE INDEX ON loans (book_id) WHERE returned_at IS NULL;
-- 3. Топ авторов: покрывающие индексы на JOIN-порядок:
--      CREATE INDEX ON books_authors (author_id, book_id);
--      CREATE INDEX ON loans (book_id) WHERE returned_at IS NULL;
-- 4. Общее: EXPLAIN (ANALYZE, BUFFERS) на реальных объёмах, смотреть
--    seq scan против index scan, nested loop против hash join; свежая
--    статистика (ANALYZE); при росте loans — партиционирование по
--    taken_at (старые партиции холодные, срезы бьют в узкий диапазон).
