package main

import "fmt"

// MultOther: res[i] = произведение всех элементов in, кроме i-го.
// [1, 2, 3] => [6, 3, 2]. O(n) по времени, O(n) под результат, без деления:
// res[i] = (произведение всего слева от i) * (произведение всего справа от i).
func MultOther(in []int) []int {
	n := len(in)
	res := make([]int, n)
	if n == 0 {
		return res
	}

	// проход влево: res[i] = произведение элементов 0..i-1
	res[0] = 1
	for i := 1; i < n; i++ {
		res[i] = res[i-1] * in[i-1]
	}

	// проход вправо: домножаем произведением элементов i+1..n-1
	suffix := 1
	for i := n - 2; i >= 0; i-- {
		suffix *= in[i+1]
		res[i] *= suffix
	}

	return res
}

func main() {
	tests := []struct {
		in   []int
		want []int
	}{
		{[]int{1, 2, 3}, []int{6, 3, 2}},
		{[]int{2, 4, 0, 3}, []int{0, 0, 24, 0}}, // один ноль: ненулевая позиция — только сам ноль
		{[]int{0, 4, 0, 3}, []int{0, 0, 0, 0}},  // два нуля: везде 0
		{[]int{1, 5}, []int{5, 1}},
		{[]int{7}, []int{1}}, // пустое произведение = 1 (договорённость)
		{nil, []int{}},
	}
	for _, t := range tests {
		got := MultOther(t.in)
		status := "OK "
		if fmt.Sprint(got) != fmt.Sprint(t.want) {
			status = "FAIL"
		}
		fmt.Printf("%s MultOther(%v) = %v\n", status, t.in, got)
	}
}

// Корнер-кейсы, уточнённые на созвоне:
//   - нули: схема префиксов/суффиксов обрабатывает их автоматически — деления
//     нет, поэтому один 0 даёт 0 везде, кроме своей позиции (там произведение
//     остальных), два нуля — 0 везде;
//   - пустой слайс — пустой результат; из одного элемента — [1]: произведение
//     пустого набора принято за 1 (на собеседовании фиксируется договорённость);
//   - переполнение int при больших значениях — уточнить у интервьюера
//     (uint64/ошибка/математика больших чисел).
